test('traces hidden pieces independently, rewinds, clears and resets on valid import only', async ({ page }) => {
  await paste(page, '1. Nf3 Nf6 2. Ng1 Ng8 3. Nf3 *');
  const selector = page.getByLabel('Trace a piece');
  await selector.selectOption('w-g1');
  await expect(page.locator('#trace-overlay line')).toHaveCount(0);
  await page.getByRole('button', { name: 'Pawns only' }).click();
  await page.getByRole('button', { name: 'Go to end', exact: true }).click();
  await expect(page.locator('#board .piece')).toHaveCount(16);
  await expect(square(page, 'f3')).toHaveCount(0);
  await expect(page.locator('#trace-overlay line')).toHaveCount(3);
  await expect(selector).toHaveValue('w-g1');
  await page.locator('[data-ply="1"]').click();
  await expect(page.locator('#trace-overlay line')).toHaveCount(1);
  await expect(page.locator('#trace-overlay line')).toHaveAttribute('data-from', 'g1');
  await expect(page.locator('#trace-overlay line')).toHaveAttribute('data-to', 'f3');
  await page.getByRole('button', { name: 'Show all', exact: true }).click();
  await expect(page.locator('#trace-overlay line')).toHaveCount(1);
  await page.getByRole('checkbox', { name: 'White Knight · g1', exact: true }).uncheck();
  await selector.selectOption('w-b1');
  await expect(page.locator('#trace-overlay line')).toHaveCount(0);
  await expect(page.locator('#trace-status')).toContainText('has not moved yet');
  await selector.selectOption('w-g1');
  await paste(page, '1. e5 *');
  await expect(selector).toHaveValue('w-g1');
  await expect(page.locator('#trace-overlay line')).toHaveCount(1);
  await expect(square(page, 'f3')).toHaveCount(0);
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(selector).toHaveValue('');
  await expect(page.locator('#trace-overlay line')).toHaveCount(0);
  await expect(square(page, 'f3')).toHaveCount(0);
  await selector.selectOption('w-g1');
  await page.screenshot({ path: 'test-results/trace.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('#trace-overlay line')).toHaveCount(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/trace-mobile.png', fullPage: true });
  await paste(page, opening);
  await expect(selector).toHaveValue('');
  await expect(page.locator('#board .piece')).toHaveCount(32);
});
